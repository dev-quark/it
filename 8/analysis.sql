CREATE TABLE IF NOT EXISTS grade_audit (
 audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 grade_id INTEGER NOT NULL,
 action VARCHAR(10) NOT NULL,
 old_grade INTEGER,
 new_grade INTEGER,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE FUNCTION log_grade_change() RETURNS TRIGGER AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  INSERT INTO grade_audit(grade_id,action,new_grade) VALUES(NEW.grade_id,TG_OP,NEW.grade);
  RETURN NEW;
 ELSIF TG_OP='UPDATE' THEN
  INSERT INTO grade_audit(grade_id,action,old_grade,new_grade) VALUES(NEW.grade_id,TG_OP,OLD.grade,NEW.grade);
  RETURN NEW;
 ELSE
  INSERT INTO grade_audit(grade_id,action,old_grade) VALUES(OLD.grade_id,TG_OP,OLD.grade);
  RETURN OLD;
 END IF;
END;
$$ LANGUAGE plpgsql;
